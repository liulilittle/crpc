// CRPC -- binary-to-text encodings and legacy character sets.
// See include/crpc/text/encoding.hpp.
//
// Every decoder here is the strict inverse of its encoder: a character outside
// the alphabet, a truncated group, padding that does not match the body, or
// non-zero bits left over after the last complete symbol is a decode_error
// naming the offset. Nothing is skipped silently and nothing is replaced,
// because an almost-correct decode is worse than a refusal: half a signature
// verifies nothing, and a dropped character looks like a different document
// rather than a corrupt one.
//
// Every encoder is a pure function of its input bytes: the same bytes always
// produce the same text, independent of platform, locale and earlier calls.
//
// The GBK mapping lives in gbk_table.inc, generated by
// .opencode/tmp/encoding/gen_gbk.py from two independent implementations
// (Python's gbk codec and glibc's iconv); it is never edited by hand.
#include <crpc/text/encoding.hpp>

#include <algorithm>
#include <cstdint>
#include <cstring>
#include <limits>
#include <vector>

#include <crpc/text/utf.hpp>

